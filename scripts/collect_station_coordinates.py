def build_station_coordinates():
    print("=== [PHASE 4] 대구 도시철도 94개 역 위경도 좌표 데이터셋 구축 ===")
    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)
    
    df = pd.DataFrame(STATIONS_MASTER, columns=['역번호', '역명', '호선', 'lon', 'lat'])
    
    # 원본 지하철 데이터와 100% 매칭 검증
    subway_df = pd.read_csv(RAW_SUBWAY_PATH, encoding='cp949')
    raw_st = set(subway_df['역번호'].unique())
    cur_st = set(df['역번호'].unique())
    
    assert raw_st == cur_st, f"역번호 불일치 발견! 누락: {raw_st - cur_st}"
    print(f"1. 원본 지하철 승하차 데이터(94개 역)와 100% 일치 확인 완료.")
    
    # 좌표 유효 범위 검증 (대구 및 연장구간 경산 일대: 128.35 ~ 128.85 E, 35.75 ~ 36.00 N)
    assert (df['lon'] >= 128.35).all() and (df['lon'] <= 128.85).all(), "경도 범위 이탈"
    assert (df['lat'] >= 35.75).all() and (df['lat'] <= 36.00).all(), "위도 범위 이탈"
    print(f"2. 전체 94개 역 좌표 유효성 검증 완료 (WGS84 EPSG:4326).")
    
    df.to_csv(OUTPUT_PATH, index=False, encoding='utf-8-sig')
    print(f"3. 저장 완료: {OUTPUT_PATH} (총 {len(df)}개 역)")

if __name__ == "__main__":
    build_station_coordinates()
